#!/usr/bin/env bash
# USwap - Linux context-menu installer
#
# Registers a "Convert with USwap" entry in Nautilus, Dolphin, Thunar and Nemo.
# Per-user only: nothing is written outside $HOME and no sudo is needed.
#
#   ./scripts/install.sh               install for the file managers it finds
#   ./scripts/install.sh --all         install for every supported file manager
#   ./scripts/install.sh --uninstall   remove everything this script created
set -euo pipefail

ACTION="install"
FORCE_ALL=0
for arg in "$@"; do
  case "$arg" in
    --uninstall) ACTION="uninstall" ;;
    --all) FORCE_ALL=1 ;;
    -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/uswap-popup"
DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
ICON_DIR="$DATA/icons/hicolor/256x256/apps"
ICON_FILE="$ICON_DIR/uswap.png"
LABEL="Convert with USwap"

NAUTILUS_SCRIPT="$DATA/nautilus/scripts/$LABEL"
NEMO_ACTION="$DATA/nemo/actions/uswap.nemo_action"
DOLPHIN_MENU="$DATA/kio/servicemenus/uswap.desktop"
THUNAR_UCA="${XDG_CONFIG_HOME:-$HOME/.config}/Thunar/uca.xml"

say()  { printf '  %s\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }

# ---------------------------------------------------------------- uninstall
remove_thunar_block() {
  [ -f "$THUNAR_UCA" ] || return 0
  grep -q 'uswap:begin' "$THUNAR_UCA" || return 0
  awk '/<!-- uswap:begin -->/{skip=1} !skip{print} /<!-- uswap:end -->/{skip=0}' \
    "$THUNAR_UCA" > "$THUNAR_UCA.tmp" && mv "$THUNAR_UCA.tmp" "$THUNAR_UCA"
}

if [ "$ACTION" = "uninstall" ]; then
  echo "Removing USwap context-menu entries..."
  rm -f "$NAUTILUS_SCRIPT" "$NEMO_ACTION" "$DOLPHIN_MENU" "$LAUNCHER" "$ICON_FILE"
  remove_thunar_block
  say "done. (The 'uswap' program itself is untouched: pipx uninstall uswap)"
  exit 0
fi

# ------------------------------------------------------------------ install
if ! have uswap; then
  echo "error: 'uswap' is not on your PATH." >&2
  echo "Install it first, e.g.:  pipx install .   (or: pip install --user .)" >&2
  exit 1
fi
USWAP_BIN="$(command -v uswap)"

echo "Installing USwap context-menu entries..."
mkdir -p "$BIN_DIR"

# 1. Launcher: file managers start us without a terminal, so open one.
cat > "$LAUNCHER" <<LAUNCH
#!/usr/bin/env bash
# Generated by USwap install.sh - opens a terminal window running uswap.
USWAP="$USWAP_BIN"
[ -x "\$USWAP" ] || USWAP="\$(command -v uswap || true)"
[ -n "\$USWAP" ] || { echo "uswap not found" >&2; exit 1; }

if [ -n "\${TERMINAL:-}" ] && command -v "\$TERMINAL" >/dev/null 2>&1; then
  term="\$TERMINAL"
else
  term=""
  for c in x-terminal-emulator gnome-terminal konsole xfce4-terminal mate-terminal \\
           kitty alacritty foot wezterm lxterminal xterm; do
    if command -v "\$c" >/dev/null 2>&1; then term="\$c"; break; fi
  done
fi
[ -n "\$term" ] || { echo "no terminal emulator found" >&2; exit 1; }

case "\$(basename "\$term")" in
  gnome-terminal)  exec "\$term" --geometry=72x26 -- "\$USWAP" "\$@" ;;
  konsole)         exec "\$term" -e "\$USWAP" "\$@" ;;
  xfce4-terminal)  exec "\$term" --geometry=72x26 -x "\$USWAP" "\$@" ;;
  mate-terminal|lxterminal) exec "\$term" -x "\$USWAP" "\$@" ;;
  kitty|foot)      exec "\$term" "\$USWAP" "\$@" ;;
  wezterm)         exec "\$term" start -- "\$USWAP" "\$@" ;;
  xterm)           exec "\$term" -geometry 72x26 -e "\$USWAP" "\$@" ;;
  *)               exec "\$term" -e "\$USWAP" "\$@" ;;
esac
LAUNCH
chmod +x "$LAUNCHER"
say "launcher      $LAUNCHER"

# 2. Icon (optional)
ICON_REF="system-run"
if [ -f "$SCRIPT_DIR/../assets/logo.png" ]; then
  mkdir -p "$ICON_DIR"
  cp "$SCRIPT_DIR/../assets/logo.png" "$ICON_FILE"
  ICON_REF="$ICON_FILE"
fi

installed=0

# 3a. Nautilus (GNOME Files) - scripts menu
if [ "$FORCE_ALL" = 1 ] || have nautilus; then
  mkdir -p "$(dirname "$NAUTILUS_SCRIPT")"
  cat > "$NAUTILUS_SCRIPT" <<NAUT
#!/usr/bin/env bash
files=()
while IFS= read -r f; do [ -n "\$f" ] && files+=("\$f"); done <<< "\${NAUTILUS_SCRIPT_SELECTED_FILE_PATHS:-}"
[ \${#files[@]} -gt 0 ] && exec "$LAUNCHER" "\${files[@]}"
NAUT
  chmod +x "$NAUTILUS_SCRIPT"
  say "nautilus      right-click > Scripts > $LABEL"
  installed=1
fi

# 3b. Nemo (Cinnamon)
if [ "$FORCE_ALL" = 1 ] || have nemo; then
  mkdir -p "$(dirname "$NEMO_ACTION")"
  cat > "$NEMO_ACTION" <<NEMO
[Nemo Action]
Name=$LABEL
Comment=Convert the selected files with USwap
Exec=$LAUNCHER %F
Icon-Name=$ICON_REF
Selection=notnone
Extensions=any;
Terminal=false
NEMO
  say "nemo          right-click > $LABEL"
  installed=1
fi

# 3c. Dolphin (KDE) - service menu (works on Plasma 5 and 6)
if [ "$FORCE_ALL" = 1 ] || have dolphin; then
  mkdir -p "$(dirname "$DOLPHIN_MENU")"
  cat > "$DOLPHIN_MENU" <<DOLPHIN
[Desktop Entry]
Type=Service
ServiceTypes=KonqPopupMenu/Plugin
MimeType=all/allfiles;
Actions=uswap;
X-KDE-Priority=TopLevel

[Desktop Action uswap]
Name=$LABEL
Icon=$ICON_REF
Exec=$LAUNCHER %F
DOLPHIN
  chmod +x "$DOLPHIN_MENU"
  say "dolphin       right-click > $LABEL"
  installed=1
fi

# 3d. Thunar (XFCE) - custom action in uca.xml
if [ "$FORCE_ALL" = 1 ] || have thunar; then
  mkdir -p "$(dirname "$THUNAR_UCA")"
  block="$(mktemp)"
  cat > "$block" <<THUNAR
<!-- uswap:begin -->
<action>
  <icon>$ICON_REF</icon>
  <name>$LABEL</name>
  <unique-id>uswap-1700000000000001</unique-id>
  <command>$LAUNCHER %F</command>
  <description>Convert the selected files with USwap</description>
  <patterns>*</patterns>
  <audio-files/>
  <image-files/>
  <other-files/>
  <text-files/>
  <video-files/>
</action>
<!-- uswap:end -->
THUNAR
  remove_thunar_block
  if [ -f "$THUNAR_UCA" ]; then
    [ -f "$THUNAR_UCA.uswap.bak" ] || cp "$THUNAR_UCA" "$THUNAR_UCA.uswap.bak"
    awk -v bf="$block" '/<\/actions>/ && !d { while ((getline l < bf) > 0) print l; d=1 } { print }' \
      "$THUNAR_UCA" > "$THUNAR_UCA.tmp" && mv "$THUNAR_UCA.tmp" "$THUNAR_UCA"
  else
    { echo '<?xml version="1.0" encoding="UTF-8"?>'; echo '<actions>'; cat "$block"; echo '</actions>'; } > "$THUNAR_UCA"
  fi
  rm -f "$block"
  say "thunar        right-click > $LABEL  (restart Thunar: thunar -q)"
  installed=1
fi

if [ "$installed" = 0 ]; then
  echo "No supported file manager detected. Re-run with --all to install anyway."
  exit 1
fi

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) echo; say "note: $BIN_DIR is not in your PATH (the menu entries still work)." ;;
esac
echo "Done. You may need to restart your file manager (e.g. 'nautilus -q')."
